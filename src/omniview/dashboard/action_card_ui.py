"""
Action Card UI Components — OI-69
====================================

Streamlit rendering components for action cards generated by the
:class:`~omniview.rules.action_cards.ActionCardGenerator`.

These components are consumed by ``app.py`` to display action cards
in the live dashboard, giving plant managers and maintenance engineers
reviewable, human-readable recommendations with physical rationale.

Usage in app.py::

    from omniview.dashboard.action_card_ui import render_action_cards_section
    render_action_cards_section(hours=24)
"""

