_CSS_INJECTED = False


def _inject_css() -> None:
    """Inject action card CSS once per session."""
    global _CSS_INJECTED  # noqa: PLW0603
    if not _CSS_INJECTED:
        st.markdown(_CARD_CSS, unsafe_allow_html=True)
        _CSS_INJECTED = True


