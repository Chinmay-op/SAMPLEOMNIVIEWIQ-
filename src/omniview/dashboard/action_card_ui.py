# ── Render a single action card ─────────────────────────────────────────


def render_action_card(card: ActionCard) -> None:
    """Render a single action card as a styled Streamlit component.

    Parameters
    ----------
    card : ActionCard
        The action card to render.
    """
    _inject_css()

    style = _SEVERITY_STYLES.get(card.severity, _SEVERITY_STYLES["INFO"])

    # ── Card container ──────────────────────────────────────────────────
    st.markdown(
        f"""
        <div class="action-card" style="
            background: {style['bg']};
            border: 1px solid {style['border']};
        ">
            <div style="display: flex; align-items: center; margin-bottom: 8px;">
                <span class="severity-badge" style="
                    background: {style['badge_bg']};
                    color: {style['badge_text']};
                ">{card.severity}</span>
                <span style="color: #8892b0; font-size: 0.75rem;">
                    {card.device_id} · {card.timestamp.strftime('%H:%M') if hasattr(card.timestamp, 'strftime') else card.timestamp}
                </span>
            </div>
            <div class="action-card-title">{card.title}</div>
            <div class="action-card-summary">{card.summary}</div>
        """,
        unsafe_allow_html=True,
    )

    # ── Badges ──────────────────────────────────────────────────────────
    badges_html = ""
    if card.rupee_impact:
        badges_html += (
            f'<span class="rupee-badge" style="'
            f"background: rgba(241, 196, 15, 0.2); "
            f"color: #f1c40f; "
            f"border: 1px solid #f39c12;"
            f'">💰 {card.rupee_impact}</span>'
        )
    if card.urgency_window:
        badges_html += f'<span class="urgency-badge">⏱️ {card.urgency_window}</span>'

    if badges_html:
        st.markdown(badges_html, unsafe_allow_html=True)

    # ── Action boxes ────────────────────────────────────────────────────
    st.markdown(
        f"""
            <div class="action-box action-box-do">
                <div class="action-box-label">✅ Recommended Action</div>
                <div class="action-box-text">{card.recommended_action}</div>
            </div>
        """,
        unsafe_allow_html=True,
    )

    if card.do_not:
        st.markdown(
            f"""
                <div class="action-box action-box-donot">
                    <div class="action-box-label">🚫 Do NOT</div>
                    <div class="action-box-text">{card.do_not}</div>
                </div>
            """,
            unsafe_allow_html=True,
        )

    # ── Target role ─────────────────────────────────────────────────────
    role_display = _ROLE_DISPLAY.get(card.target_role, card.target_role)
    st.markdown(
        f'<div class="target-role">Route to: {role_display}</div>',
        unsafe_allow_html=True,
    )

    # ── Close card container ────────────────────────────────────────────
    st.markdown("</div>", unsafe_allow_html=True)

    # ── Expandable sections (for internal review) ───────────────────────
    with st.expander("🔬 Physical Rationale (internal review)"):
        st.markdown(card.physical_rationale or "_No rationale provided._")

    with st.expander("📊 Source Sensor Readings"):
        if card.sensor_readings:
            for k, v in card.sensor_readings.items():
                st.text(f"  {k}: {v}")
        else:
            st.text("  No sensor readings attached.")


# ── Section renderer ────────────────────────────────────────────────────


def render_action_cards_section(cards: list[ActionCard]) -> None:
    """Render the full action cards section in the dashboard.

    Parameters
    ----------
    cards : list[ActionCard]
        Action cards to display, typically from ``get_action_cards()``.
    """
    _inject_css()

    st.markdown(
        '<p class="section-header">🎯 Action Cards</p>',
        unsafe_allow_html=True,
    )

    if not cards:
        st.info(
            "No action cards generated. Cards appear when rule/PdM events "
            "or scenario-labeled readings are detected."
        )
        return

    # Summary counts
    critical = sum(1 for c in cards if c.severity == "CRITICAL")
    warning = sum(1 for c in cards if c.severity == "WARNING")
    info_ = sum(1 for c in cards if c.severity == "INFO")

    scol1, scol2, scol3, scol4 = st.columns(4)
    with scol1:
        st.metric("Total Cards", len(cards))
    with scol2:
        st.metric("🔴 Critical", critical)
    with scol3:
        st.metric("🟡 Warning", warning)
    with scol4:
        st.metric("🔵 Info", info_)

    st.markdown("---")

    # Render cards — critical first
    sorted_cards = sorted(
        cards,
        key=lambda c: {"CRITICAL": 0, "WARNING": 1, "INFO": 2}.get(c.severity, 3),
    )

    for card in sorted_cards:
        render_action_card(card)
